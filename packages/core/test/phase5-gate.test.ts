// Phase 5 gate — Requirement 18.7, as one measured comparison on a fixed
// fifty-file fixture, offline, with no key.
//
// THE CLAIM BEING TESTED, in the requirement's own words: "AGAINST a fixed
// fifty-file fixture THE targeted context SHALL be smaller and more relevant than
// the whole-repo baseline AND the held-out eval score SHALL rise."
//
// Three measurements, one fixture:
//   1. SMALLER   — assembled tokens vs. the whole repository's tokens.
//   2. MORE RELEVANT — of the files put in front of the model, what share belong to
//      the domain the question is about, and is the answering file there at all.
//   3. THE SCORE RISES — the eval harness, scored twice over the same cases: once
//      with targeted context, once with the whole repository truncated to the SAME
//      token budget. Both numbers are printed.
//
// ── THE BASELINE IS NOT A STRAWMAN ──────────────────────────────────────────
//
// "Whole-repo baseline" is implemented the way anyone actually does it: concatenate
// every indexed file, in the graph's order, and stop when the token budget runs out.
// Nothing is shuffled to make it lose. The fixture's domains sort alphabetically, so
// `src/auth/…` lands inside the budget and the baseline ANSWERS THE AUTH QUESTION
// CORRECTLY — that case is deliberately in the held-out split, so the reported rise
// is 1/3 → 3/3 rather than 0 → 1. A baseline that scored zero would prove nothing
// except that the fixture was built to embarrass it.
//
// ── WHAT "HELD-OUT" MEANS HERE, HONESTLY ────────────────────────────────────
//
// There is no training in this phase, so "held-out" cannot mean "not trained on".
// It means not tuned on. Two knobs had to be chosen — the token budget and topK —
// and they were chosen by looking at the two DEV cases only (catalog, payments). The
// three HELD-OUT cases (auth, inventory, shipping) were not consulted while
// choosing them, and the requirement's assertion is made on that split. The dev
// numbers are printed too, because hiding them would be the easy way to cheat this.
//
// ── WHAT THIS FILE DOES NOT PROVE ───────────────────────────────────────────
//
// `ContextFaithfulAdapter` is NOT a model. It answers from the text it was handed
// and refuses when the fact is not there. That makes it a measuring instrument for
// exactly one thing — did the right evidence reach the prompt — and it is the only
// thing this file claims. It says nothing about whether a real model reasons better
// with a smaller context, and nothing in this repository has ever run against a real
// provider. A gate that used a real model would measure the model's mood as much as
// the retriever's quality, and could not run offline at $0.
//
// Everything else here is real: real files on disk, the real walker, chunker and
// import extractor via `buildRepoGraph`, the real hybrid retriever (scanner engine
// forced so both machines agree), the real hashing embedder and vector store, the
// real assembly with its real budget enforcement, the real eval harness, and the
// real architecture generator.
//
// Validates: Requirements 18.7, 18.2, 18.4, 18.5, 18.6, 18.8, 19.1, 19.4, 19.5

