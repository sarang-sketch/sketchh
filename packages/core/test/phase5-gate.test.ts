// ── knobs, and where they came from ─────────────────────────────────────────

/**
 * The token budget both sides are held to. Chosen against the DEV cases only.
 *
 * At `chars/4` this is ~6 000 characters: roughly five of the fixture's files, so
 * the baseline has to choose and the assembly has to degrade. A budget large enough
 * to hold the whole fixture would make the comparison meaningless.
 */
const BUDGET_TOKENS = 1_500

/** Chunks retrieval returns. Also chosen on the dev cases only. */
const TOP_K = 6

// ── the fifty-file fixture ──────────────────────────────────────────────────
//
// Ten domains, five files each. Five domains carry a distinctive CONFIGURATION FACT
// that appears nowhere else in the tree; the other five are the same shape with
// their own vocabulary, so they are plausible neighbours rather than filler.
//
// The fixture is generated by code rather than checked in as fifty files so that it
// is auditable in one screen: if a domain could answer another domain's question,
// you can see it here.

interface Needle {
  /** Directory under `src/`. */
  domain: string
  /** The question a user would actually type. Prose, not an identifier. */
  query: string
  /** The constant that answers it. */
  constant: string
  /** Its value, as it is spelled in the source. */
  value: string
  /** Lower-case words that belong in the file's doc comment. */
  prose: string
}

/**
 * The five answerable questions.
 *
 * `auth` sorts first of all ten domains, which is exactly why it is in the held-out
 * split: the baseline reaches it, and the gate has to survive that.
 */
