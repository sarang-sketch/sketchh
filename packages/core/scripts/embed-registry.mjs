// Embed the curated skill registry into the engine, so a shipped app can install skills.
//
// The registry is a folder of files (`registry/registry.json` plus one folder per
// skill) whose digests the installer re-verifies from disk. The desktop sidecar is ONE
// bundled file with nothing beside it, so "the registry ships under registry/" was true
// of the npm package and false of the app: the Skills panel said no registry was
// configured. This writes the exact bytes into `src/registry/embedded.ts` (base64, so
// no line ending or escape can alter a digest); the engine materializes them into
// `~/.sketch/registry/` on first use and installs from there with the SAME verification.
//
//   node scripts/embed-registry.mjs          rewrite src/registry/embedded.ts
//   node scripts/embed-registry.mjs --check  exit 1 if it is out of date
//
// `test/registry.embedded.test.ts` also fails when the two disagree, so a registry
// change that forgets this step cannot pass the suite.

import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = join(here, '..')
const registryDir = join(pkg, 'registry')
const target = join(pkg, 'src', 'registry', 'embedded.ts')

/** registry.json plus every file under skills/, sorted, POSIX paths. */
function collect() {
  const files = [['registry.json', readFileSync(join(registryDir, 'registry.json'))]]
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) walk(path)
      else files.push([relative(registryDir, path).split(sep).join('/'), readFileSync(path)])
    }
  }
  walk(join(registryDir, 'skills'))
  return files
}

export function render() {
  const files = collect()
  const digest = createHash('sha256')
  for (const [path, bytes] of files) {
    digest.update(path).update('\0').update(createHash('sha256').update(bytes).digest('hex')).update('\n')
  }
  const lines = [
    '// GENERATED by scripts/embed-registry.mjs from packages/core/registry. Do not edit.',
    '// The curated skill registry, byte for byte, so the bundled engine can install skills',
    '// with no files beside it. See the script header for why it exists.',
    '',
    '/** sha256 over (path, file sha256) pairs; names the materialized folder. */',
    `export const EMBEDDED_REGISTRY_DIGEST = '${digest.digest('hex')}'`,
    '',
    '/** Registry-relative POSIX path → base64 bytes. */',
    'export const EMBEDDED_REGISTRY_FILES: Readonly<Record<string, string>> = Object.freeze({',
    ...files.map(([path, bytes]) => `  ${JSON.stringify(path)}: ${JSON.stringify(bytes.toString('base64'))},`),
    '})',
    '',
  ]
  return lines.join('\n')
}

const check = process.argv.includes('--check')
const next = render()
let current = ''
try {
  current = readFileSync(target, 'utf8')
} catch {
  current = ''
}
if (check) {
  if (current !== next) {
    console.error('src/registry/embedded.ts is out of date: run node scripts/embed-registry.mjs')
    process.exit(1)
  }
  console.log('embedded registry is up to date')
} else {
  writeFileSync(target, next)
  console.log(`wrote ${relative(pkg, target)}`)
}
