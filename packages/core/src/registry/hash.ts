// The canonical content hash of a skill directory.
//
// ── WHY THE WHOLE DIRECTORY, NOT `SKILL.md` ─────────────────────────────────
//
// A skill is prose PLUS executables. `awesome-llm-apps`' skills ship Python; the
// folder layout this project already reads has `tools/`, `workflows/` and
// `tests/` directories. Hashing only the markdown would leave the part that
// actually runs on the user's machine unprotected, which is the wrong half to
// protect. So every file under the skill root is hashed, and the path is hashed
// with it: moving a script from `tools/safe.py` to `tools/run.py` changes the
// digest even though no byte of content changed.
//
// ── THE ALGORITHM, WRITTEN DOWN SO A THIRD PARTY CAN REPRODUCE IT ───────────
//
//   1. Walk the skill directory recursively. Collect every FILE.
//   2. Make each path relative to the skill root, with `/` separators.
//      Skip the entries named in `IGNORED_ENTRIES` (see below).
//   3. Sort the relative paths by UTF-16 code unit, ascending. Not
//      `localeCompare` — that varies by host locale and would make the digest
//      machine-dependent.
//   4. For each file, in that order, compute `sha256(bytes)` as lowercase hex.
//   5. Build the manifest line `<relative-path>\0<file-sha256>\n` for each, and
//      concatenate them in order.
//   6. The directory digest is `sha256` of that concatenation, lowercase hex,
//      prefixed `sha256:`.
//
// FILES ARE READ AS BYTES, NEVER AS STRINGS. A skill checked out on Windows with
// `core.autocrlf=true` has different bytes from the same skill on Linux, and
// reading as utf8 then re-encoding would silently paper over that — meaning a
// tampered file could match, or an untampered one could fail. The bytes are the
// artifact. A CRLF checkout producing a different digest is CORRECT behaviour,
// and `.gitattributes` is how a publisher stops it happening.
//
// `node:crypto` is a builtin, so this obeys the zero-dependency rule.
//
// Validates: Requirements 11.1, 11.2

import { createHash } from 'node:crypto'
import { readFile, readdir } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'

/** Digest prefix, so a stored digest names its own algorithm. */
export const DIGEST_PREFIX = 'sha256:'

/**
 * Entries excluded from the digest, matched on the exact basename at any depth.
 *
 * Deliberately short. Each entry is something a checkout or an editor creates
 * that the publisher did not sign, and every addition here is a hole in the
 * protection, so nothing goes in without that argument:
 *   * `.git` — a clone's own metadata. Never part of a published skill.
 *   * `node_modules` — installed, not authored.
 *   * `__pycache__`, `.pytest_cache` — generated by running the skill's own
 *     Python, so a skill that was executed once would otherwise stop verifying.
 *   * `.DS_Store`, `Thumbs.db` — created by a file browser merely looking.
 *
 * NOT excluded: `.env`, dotfiles in general, anything under `tools/`. A skill
 * shipping a dotfile is signing it.
 */
export const IGNORED_ENTRIES: readonly string[] = [
  '.git',
  'node_modules',
  '__pycache__',
  '.pytest_cache',
  '.DS_Store',
  'Thumbs.db',
]

/** One file's contribution to the digest. */
export interface FileDigest {
  /** Project-relative, POSIX separators. */
  path: string
  /** `sha256:<hex>` of the file's bytes. */
  digest: string
  bytes: number
}

/** The digest of a directory, plus the per-file digests it was built from. */
export interface DirectoryDigest {
  /** `sha256:<hex>` over the canonical manifest. What a registry entry pins. */
  digest: string
  /** Every hashed file, in the exact order they were folded in. */
  files: FileDigest[]
  /** The canonical manifest text the digest was taken over. Debugging aid. */
  manifest: string
}

function hex(input: Buffer | string): string {
  return createHash('sha256').update(input).digest('hex')
}

/** `sha256:<hex>` of a byte buffer. */
export function hashBytes(bytes: Buffer): string {
  return `${DIGEST_PREFIX}${hex(bytes)}`
}

/** POSIX-separated path relative to `root`. */
function relativePosix(root: string, path: string): string {
  return relative(root, path).split(sep).join('/')
}

/** Locale-independent ordering. See step 3 of the algorithm. */
function comparePaths(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

/**
 * Every file under `dir`, as relative POSIX paths, sorted, ignoring
 * {@link IGNORED_ENTRIES}. Exported because the installer copies exactly this
 * set — the file list that is hashed and the file list that is written must not
 * be able to disagree.
 */
export async function skillFiles(dir: string): Promise<string[]> {
  const found: string[] = []

  const walk = async (current: string): Promise<void> => {
    const entries = await readdir(current, { withFileTypes: true })
    for (const entry of entries) {
      if (IGNORED_ENTRIES.includes(entry.name)) continue
      const full = join(current, entry.name)
      if (entry.isDirectory()) {
        await walk(full)
        continue
      }
      // A symlink is NOT followed and NOT hashed. Following one would let a
      // skill's digest cover bytes outside its own directory — or hash the
      // user's `~/.ssh/id_rsa` into a published manifest.
      if (!entry.isFile()) continue
      found.push(relativePosix(dir, full))
    }
  }

  await walk(dir)
  return found.sort(comparePaths)
}

/** The canonical manifest line for one file. Step 5 of the algorithm. */
export function manifestLine(path: string, digest: string): string {
  return `${path}\u0000${digest}\n`
}

/**
 * Hash a skill directory. Pure function of the bytes on disk: same tree, same
 * digest, on any machine and in any locale.
 */
export async function hashSkillDirectory(dir: string): Promise<DirectoryDigest> {
  const paths = await skillFiles(dir)

  const files: FileDigest[] = []
  let manifest = ''
  for (const path of paths) {
    // Bytes. Not utf8. See the header.
    const bytes = await readFile(join(dir, path))
    const digest = hashBytes(bytes)
    files.push({ path, digest, bytes: bytes.byteLength })
    manifest += manifestLine(path, digest)
  }

  return { digest: `${DIGEST_PREFIX}${hex(manifest)}`, files, manifest }
}

/** How a computed digest differs from a pinned one, file by file. */
export interface DigestDifference {
  path: string
  /** What the manifest pinned, or null when the file is new. */
  expected: string | null
  /** What is on disk, or null when the file is missing. */
  actual: string | null
  kind: 'added' | 'removed' | 'changed'
}

/**
 * Compare a pinned file list against a computed one.
 *
 * This exists so a tamper diagnostic can name THE FILE rather than saying "hash
 * mismatch". "Something in this skill changed" is unactionable; "`tools/run.py`
 * differs from the manifest" tells the user what to look at, and tells a
 * publisher what they forgot to re-pin.
 */
export function diffDigests(
  expected: readonly FileDigest[],
  actual: readonly FileDigest[],
): DigestDifference[] {
  const byPathExpected = new Map(expected.map((file) => [file.path, file.digest]))
  const byPathActual = new Map(actual.map((file) => [file.path, file.digest]))
  const differences: DigestDifference[] = []

  for (const [path, digest] of byPathExpected) {
    const found = byPathActual.get(path)
    if (found === undefined) {
      differences.push({ path, expected: digest, actual: null, kind: 'removed' })
    } else if (found !== digest) {
      differences.push({ path, expected: digest, actual: found, kind: 'changed' })
    }
  }
  for (const [path, digest] of byPathActual) {
    if (!byPathExpected.has(path)) {
      differences.push({ path, expected: null, actual: digest, kind: 'added' })
    }
  }

  return differences.sort((a, b) => comparePaths(a.path, b.path))
}

/** One-line, human-readable rendering of a difference. */
export function describeDifference(difference: DigestDifference): string {
  switch (difference.kind) {
    case 'added':
      return `${difference.path}: present on disk but not in the manifest`
    case 'removed':
      return `${difference.path}: named in the manifest but missing on disk`
    case 'changed':
      return `${difference.path}: content differs (manifest ${short(difference.expected)}, on disk ${short(difference.actual)})`
  }
}

/** First 12 hex characters after the prefix. Enough to compare by eye. */
function short(digest: string | null): string {
  if (digest === null) return 'absent'
  const hexPart = digest.startsWith(DIGEST_PREFIX) ? digest.slice(DIGEST_PREFIX.length) : digest
  return `${DIGEST_PREFIX}${hexPart.slice(0, 12)}…`
}
